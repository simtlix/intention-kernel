import { readdir, readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";

const generatedFiles = [new URL("../api-reports/intention-kernel.api.md", import.meta.url), new URL("../api-reports/intention-kernel-testing.api.md", import.meta.url)];
const runtimePackage = new URL("../docs/reference/intention-kernel.md", import.meta.url);
const testingDirectory = new URL("../docs/reference/testing/", import.meta.url);
await collectMarkdownFiles(new URL("../docs/reference/", import.meta.url), generatedFiles);

for (const file of generatedFiles) {
  const content = await readFile(file, "utf8");
  let normalized = content.replace(/\r\n?/gu, "\n");
  if (file.href.startsWith(testingDirectory.href)) {
    normalized = normalized
      .replaceAll("[intention-kernel](./intention-kernel.md)", "[intention-kernel/testing](./intention-kernel.md)")
      .replace("## intention-kernel package", "## intention-kernel/testing package");
  }
  if (file.href === runtimePackage.href && !normalized.includes("<!-- entry-point-navigation -->")) {
    normalized = normalized.replace("## Classes\n", [
      "<!-- entry-point-navigation -->",
      "Import these runtime APIs from `intention-kernel`. For scenario evaluation, assertions, reports, and test helpers, see [intention-kernel/testing](./testing/intention-kernel.md).",
      "",
      "## Classes",
      "",
    ].join("\n"));
  }
  if (file.href.includes("/docs/reference/") && !/^# /m.test(normalized)) {
    normalized = normalized.replace(/^## /m, "# ");
  }
  // Preserve Markdown hard breaks while removing whitespace in generated code.
  normalized = normalized.replace(/(^```[^\n]*\n)([\s\S]*?)(^```)/gm,
    (_match, opening, code, closing) => opening + code.replace(/[ \t]+$/gm, "") + closing,
  ).trimEnd() + "\n";
  if (normalized !== content) {
    await writeFile(file, normalized, "utf8");
  }
}

// API Documenter generates each entry point independently. Join their indexes
// so the reference home exposes every supported public import after regeneration.
await writeFile(new URL("../docs/reference/index.md", import.meta.url), [
  "<!-- Generated by API Documenter and scripts/normalize-generated-docs.mjs. -->",
  "",
  "# API reference",
  "",
  "Intention Kernel exposes two public entry points. Select the package whose APIs you need, or read the [API overview](../api.md).",
  "",
  "| Import | API |",
  "| --- | --- |",
  "| [intention-kernel](./intention-kernel.md) | Agent definitions, capabilities, compilation, execution, and runtime contracts. |",
  "| [intention-kernel/testing](./testing/intention-kernel.md) | Declarative evaluations, assertions, adapters, reports, and in-memory test helpers. |",
  "",
].join("\n"), "utf8");

await writeFile(new URL("index.md", testingDirectory), [
  "<!-- Generated by API Documenter and scripts/normalize-generated-docs.mjs. -->",
  "",
  "# Testing API reference",
  "",
  "Import these APIs from `intention-kernel/testing` in your application.",
  "",
  "- [Testing exports and signatures](./intention-kernel.md)",
  "- [Testing API overview](../../api.md#testing-subpath)",
  "- [Evaluating from your project](../../guide/evaluation/quick-start.md)",
  "- [All public entry points](../index.md)",
  "",
].join("\n"), "utf8");

async function collectMarkdownFiles(directory, files) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const entryUrl = new URL(entry.name, directory);
    if (entry.isDirectory()) {
      await collectMarkdownFiles(new URL(`${entry.name}/`, directory), files);
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push(entryUrl);
    }
  }
}
